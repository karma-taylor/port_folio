import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const source = await readFile(join(root, "data/projects.js"), "utf8");
const dataUrl = `data:text/javascript;base64,${Buffer.from(source).toString("base64")}`;
const { PROJECTS: SOURCE_PROJECTS, PROJECT_MANAGEMENT_META = {} } = await import(dataUrl);

const ASSET_VERSION = "20261025-vivid";
const PROJECTS = [...SOURCE_PROJECTS]
  .sort((a, b) => (a.homeOrder ?? 99) - (b.homeOrder ?? 99))
  .map((project, position) => ({ ...project, index: String(position + 1).padStart(2, "0") }));

const routes = {
  calendar: "work-calendar",
  "enterprise-rag": "enterprise-policy-rag",
  digest: "daily-digest",
  money: "money-distribute",
  fx: "weather-fx-agent",
  report: "daily-report-engine",
};
const images = {
  calendar: ["calendar-cover-auto.png", "calendar-cover.jpg"],
  "enterprise-rag": ["assets/cases/enterprise-rag/qa.webp", "assets/cases/enterprise-rag/xray.webp", "assets/cases/enterprise-rag/admin.webp"],
  digest: ["digest-cover-auto.png", "digest-cover.png"],
  money: ["money-cover-auto.png", "money-cover.png"],
  fx: ["fx-cover-auto.png", "fx-cover.jpg"],
  report: ["report-cover.png"],
};
const origin = "https://www.vinanverse.com";
const isLocalAsset = (file) => file.startsWith("assets/");
const rootAsset = (file) => isLocalAsset(file) ? `./${file}` : `${origin}/${file}`;
const caseAsset = (file) => isLocalAsset(file) ? `../../${file}` : `${origin}/${file}`;
const socialAsset = (file) => `${origin}/${file}`;
const evidenceNotice = (project) => project.id === "enterprise-rag"
  ? "公开合成数据界面；不包含真实企业文档、个人信息或私有评测数据。"
  : "公开项目截图；仅用于展示产品界面与信息结构。";
const ragShotMeta = [
  { alt: "企业制度 RAG 员工问答页，展示财务角色的授权答案与引用证据", caption: "员工问答页" },
  { alt: "企业制度 RAG X-Ray 页，展示权限范围、证据引用与检索轨迹", caption: "X-Ray 权限与证据轨迹页" },
  { alt: "企业制度 RAG 只读知识治理页，展示公开合成制度资料的治理状态", caption: "只读知识治理页" },
];
const esc = (value = "") => String(value).replace(/[&<>\"]/g, (char) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[char]);
const richText = (parts = []) => (Array.isArray(parts) ? parts : [parts]).map((part) => {
  if (typeof part === "string") return esc(part);
  return part?.strong ? `<strong>${esc(part.text)}</strong>` : esc(part?.text);
}).join("");
const linkByType = (project, type) => project.detail?.links?.find((link) => link.type === type);
const publicProject = (project) => {
  const meta = PROJECT_MANAGEMENT_META[project.id] || {};
  return {
    id: project.id,
    index: project.index,
    slug: routes[project.id],
    tier: project.tier || "more",
    title: project.title,
    titleLong: project.titleLong,
    statusLabel: project.statusLabel,
    summary: project.detail?.summary || project.hoverValue,
    tagline: project.detail?.focus?.tagline || project.hoverValue,
    role: meta.role || "",
    scenario: meta.scenario || "",
    verification: meta.verification || "",
    results: project.detail?.recruiting?.results || [],
    cover: rootAsset(images[project.id][0]),
    coverAlt: project.cover?.alt || `${project.title} 项目界面`,
    live: linkByType(project, "live") || null,
    github: linkByType(project, "github") || project.github || null,
  };
};

const cases = PROJECTS.map(publicProject);
await writeFile(join(root, "data/case-manifest.js"), `// Generated by tools/build-case-pages.mjs. Edit data/projects.js, then rerun this script.\nexport const CASES = ${JSON.stringify(cases, null, 2)};\n`, "utf8");

function action(link, label, className, track, slug) {
  if (!link?.href) return "";
  return `<a class="${className}" href="${esc(link.href)}" target="_blank" rel="noopener noreferrer" data-track="${track}" data-track-label="${esc(slug)}">${esc(label)} <span aria-hidden="true">↗</span></a>`;
}
function screenshots(project) {
  const files = images[project.id] || [];
  const synthetic = project.id === "enterprise-rag";
  return files.map((file, index) => {
    const shot = synthetic ? ragShotMeta[index] : null;
    const alt = shot?.alt || `${project.cover?.alt || project.title} — ${index ? "补充界面" : "项目主界面"}`;
    const caption = shot?.caption || (index ? "补充界面" : "产品主界面");
    return `<figure class="case-shot case-shot--${index + 1}"><button type="button" data-image-dialog data-image-src="${caseAsset(file)}" data-image-alt="${esc(alt)}"><img src="${caseAsset(file)}" alt="${esc(alt)}" loading="lazy" /></button><figcaption>${esc(caption)} / ${synthetic ? "公开合成数据" : "公开项目截图"}</figcaption></figure>`;
  }).join("");
}
function proseCards(items) {
  return `<div class="case-prose">${items.filter(([, value]) => value).map(([label, value]) => `<p><strong>${esc(label)}</strong>${esc(value)}</p>`).join("")}</div>`;
}
function sectionHeading(number, title) {
  return `<h2><span class="case-section-number">${number}</span>${esc(title)}</h2>`;
}

function contextSection(project, meta, number) {
  const recruiting = project.detail?.recruiting || {};
  const focus = project.detail?.focus || {};
  const story = meta.userStory || {};
  const storyBlock = story.actor
    ? `<div class="user-story"><p class="user-story__actor"><small>典型用户</small>${esc(story.actor)}</p><dl>${[
        ["情境", story.situation],
        ["需要", story.need],
        ["风险", story.risk],
      ].filter(([, value]) => value).map(([label, value]) => `<div><dt>${label}</dt><dd>${esc(value)}</dd></div>`).join("")}</dl></div>`
    : "";
  return `<section class="case-section shell case-context">${sectionHeading(number, "背景与用户")}${proseCards([
    ["使用场景", recruiting.usersScene || meta.scenario],
    ["核心问题", recruiting.coreProblem || focus.problem],
    ["本轮范围", recruiting.researchScope],
    ["为什么做", recruiting.background],
  ])}${storyBlock}</section>`;
}
function solutionSection(project, number) {
  const focus = project.detail?.focus || {};
  const steps = project.flow?.steps || [];
  return `<section class="case-section shell case-solution">${sectionHeading(number, "方案与取舍")}${proseCards([
    ["我负责的部分", focus.ownership],
    ["关键取舍", focus.productJudgment],
  ])}</section>
<section class="case-section case-system"><p class="case-system__label">方案路径</p><div class="flow-board" aria-label="${esc(project.flow?.ariaLabel || project.title)} 流程">${steps.map((step, index) => `<div class="flow-step ${step.accent ? "is-accent" : ""}"><span>${esc(step.idx)}</span><strong>${esc(step.label)}</strong>${index < steps.length - 1 ? "<i aria-hidden=\"true\"></i>" : ""}</div>`).join("")}</div><p>${esc(focus.flowSummary || "以明确规则收束输入、判断与输出。")}</p></section>`;
}
function resultSection(project, number) {
  const results = project.detail?.recruiting?.results || [];
  const outcomes = project.outcomes || [];
  return `<section class="case-section shell case-results">${sectionHeading(number, "结果与指标")}<dl class="result-grid result-grid--large">${results.map((item) => `<div><dt>${esc(item.label)}</dt><dd>${esc(item.value)}</dd></div>`).join("")}</dl>${outcomes.length ? `<ul class="outcome-list">${outcomes.map((item) => `<li>${esc(item)}</li>`).join("")}</ul>` : ""}</section>`;
}
function evidenceSection(project, number) {
  const intro = project.id === "enterprise-rag"
    ? "以下界面均来自本地公开合成数据 Demo；真实语料、私有评测与密钥均不进入作品集。"
    : "以下内容均来自公开项目界面或公开运行输出，不包含客户、人员与财务敏感数据。";
  return `<section class="case-section shell case-evidence">${sectionHeading(number, "交付证据")}<p class="case-section-intro">${intro}</p><div class="case-gallery">${screenshots(project)}</div></section>`;
}
function boundarySection(project, meta, number) {
  const recruiting = project.detail?.recruiting || {};
  return `<section class="case-section shell case-delivery">${sectionHeading(number, "风险与边界")}<div class="delivery-grid"><p><strong>交付内容</strong>${esc(recruiting.delivery || "完成可复核的产品交付。")}</p><p><strong>验收方式</strong>${esc(meta.verification || "以公开版本和可复现流程进行核验。")}</p><p><strong>下一步与边界</strong>${esc(recruiting.risks || "持续在真实使用中迭代。")}</p></div></section>`;
}
function retrospectiveSection(project, number) {
  const sections = project.detail?.retrospective?.sections;
  if (!sections?.length) return "";
  return `<section class="case-section shell case-retrospective">${sectionHeading(number, "复盘")}<div class="retrospective-list">${sections.map((section) => `<article><h3>${esc(section.label)}</h3><p class="retrospective-lead">${section.summary.map(richText).join("")}</p><ul>${section.points.map((point) => `<li>${richText(point)}</li>`).join("")}</ul></article>`).join("")}</div></section>`;
}
function contactSection(project) {
  const slug = routes[project.id];
  return `<section class="case-contact shell"><div><p class="case-kicker">联系</p><h2>想进一步了解这个项目？</h2><p>我可以现场演示规则、校验和验收过程，也可以聊聊它在你们业务里怎么落地。</p></div><div class="case-contact__actions"><a class="case-button case-button--dark" href="../../resume.pdf" download="郭伟南-产品经理简历.pdf" data-track="resume_download" data-track-label="case-${esc(slug)}">下载简历 PDF <span aria-hidden="true">↓</span></a><a class="case-button" href="mailto:taylorkarma@163.com" data-track="email_click" data-track-label="case-${esc(slug)}">taylorkarma@163.com <span aria-hidden="true">↗</span></a><details class="qr-pop qr-pop--up"><summary class="case-button case-button--quiet" data-track="wechat_open" data-track-label="case-${esc(slug)}">微信</summary><div class="qr-pop__panel"><img src="../../wechat-qr.png" alt="郭伟南的微信二维码" width="180" height="180" loading="lazy" /><span>扫码添加微信</span></div></details></div></section>`;
}

function page(project, position) {
  const details = project.detail || {};
  const focus = details.focus || {};
  const meta = PROJECT_MANAGEMENT_META[project.id] || {};
  const slug = routes[project.id];
  const previous = PROJECTS[(position + PROJECTS.length - 1) % PROJECTS.length];
  const next = PROJECTS[(position + 1) % PROJECTS.length];
  const heroImage = caseAsset(images[project.id][0]);
  const socialImage = socialAsset(images[project.id][0]);
  const canonical = `${origin}/cases/${slug}/`;
  const github = linkByType(project, "github") || project.github;
  const live = linkByType(project, "live");
  const external = live || github;
  const snapshot = [
    ["我的角色", meta.role],
    ["业务场景", meta.scenario],
    ["当前状态", meta.status || project.statusLabel],
    ["验证方式", meta.verification],
  ].filter(([, value]) => value);

  const bodySections = [
    (n) => contextSection(project, meta, n),
    (n) => solutionSection(project, n),
    (n) => resultSection(project, n),
    (n) => evidenceSection(project, n),
    (n) => boundarySection(project, meta, n),
    project.detail?.retrospective?.sections?.length ? (n) => retrospectiveSection(project, n) : null,
  ].filter(Boolean).map((render, index) => render(String(index + 1).padStart(2, "0"))).join("\n");

  return `<!doctype html>
<html lang="zh-CN"><head><meta charset="UTF-8" /><meta name="viewport" content="width=device-width, initial-scale=1.0" /><script>document.documentElement.classList.add("js");</script>
<title>${esc(project.titleLong)} · 郭伟南作品集</title><meta name="description" content="${esc(details.summary || focus.tagline || project.hoverValue)}" />
<link rel="canonical" href="${canonical}" /><meta property="og:type" content="article" /><meta property="og:title" content="${esc(project.titleLong)} · 郭伟南作品集" /><meta property="og:description" content="${esc(details.summary || focus.tagline || project.hoverValue)}" /><meta property="og:url" content="${canonical}" /><meta property="og:image" content="${socialImage}" />
<link rel="preconnect" href="https://fonts.googleapis.com" /><link rel="preconnect" href="https://fonts.gstatic.com" crossorigin /><link href="https://fonts.googleapis.com/css2?family=DM+Mono:wght@400;500&family=Manrope:wght@400;500;600;700;800&family=Noto+Sans+SC:wght@400;500;600;700;800&display=swap" rel="stylesheet" /><link rel="stylesheet" href="../../styles.css?v=${ASSET_VERSION}" />
<script type="application/ld+json">${JSON.stringify({ "@context": "https://schema.org", "@type": "CreativeWork", name: project.titleLong, description: details.summary || focus.tagline, url: canonical, image: socialImage, author: { "@type": "Person", name: "郭伟南", alternateName: "Karma Taylor" } })}</script></head>
<body class="case-page"><div class="grain" aria-hidden="true"></div><header class="case-header"><a class="brand" href="../../" aria-label="返回作品集首页"><span class="brand-mark">郭</span><span>郭伟南<small>Karma Taylor</small></span></a><div class="case-header__links"><a class="back-link" href="../../#work"><span aria-hidden="true">←</span> 全部案例</a><a class="header-resume" href="../../resume.pdf" download="郭伟南-产品经理简历.pdf" data-track="resume_download" data-track-label="case-header-${esc(slug)}">下载简历 <i aria-hidden="true">↓</i></a></div></header>
<main><section class="case-hero shell"><div class="case-hero-copy reveal"><p class="case-kicker">${esc(project.index)} / ${esc(project.statusLabel || "PROJECT CASE")}</p><h1>${esc(project.titleLong)}</h1><p>${esc(focus.tagline || project.hoverValue)}</p><div class="case-actions">${action(external, live ? "访问上线版本" : "查看 GitHub", "case-button case-button--dark", live ? "live_open" : "github_open", slug)}${live && github?.href ? action(github, "查看 GitHub", "case-button case-button--quiet", "github_open", slug) : ""}</div></div><figure class="case-hero-media reveal"><img src="${heroImage}" alt="${esc(project.cover?.alt || project.title)}" /><figcaption>${evidenceNotice(project)}</figcaption></figure></section>
<section class="case-intro shell" aria-label="案例速览"><div><p class="case-kicker">速览</p><p class="case-intro__summary">${esc(details.summary || project.hoverValue)}</p></div><dl class="case-snapshot">${snapshot.map(([label, value]) => `<div><dt>${label}</dt><dd>${esc(value)}</dd></div>`).join("")}</dl></section>
${bodySections}
${contactSection(project)}
<nav class="case-pagination shell" aria-label="案例导航"><a href="../${routes[previous.id]}/"><small>上一案例</small><strong>${esc(previous.title)}</strong></a><a href="../${routes[next.id]}/"><small>下一案例</small><strong>${esc(next.title)}</strong></a></nav></main>
<dialog class="image-dialog" aria-label="查看项目截图"><button type="button" class="image-dialog-close" data-image-close aria-label="关闭截图">×</button><img src="${heroImage}" alt="${esc(project.cover?.alt || project.title)}" /></dialog><script type="module" src="../../analytics.js?v=${ASSET_VERSION}"></script><script type="module" src="../../case.js?v=${ASSET_VERSION}"></script></body></html>`;
}

for (const [position, project] of PROJECTS.entries()) {
  const directory = join(root, "cases", routes[project.id]);
  await mkdir(directory, { recursive: true });
  await writeFile(join(directory, "index.html"), page(project, position), "utf8");
}

console.log(`Generated ${PROJECTS.length} case pages and data/case-manifest.js.`);
